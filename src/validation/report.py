    if ident:
        L += ["## 10. Accounting identity", "", f"λ = 0 run over {ident['n_possessions']:,} possessions: max |Σ components − G_p| = {ident['max_abs_residual']:.2e}, mean = {ident['mean_abs_residual']:.2e}.", ""]
    # ------------------------------------------------------------------ leaderboards
    lb = cfg.path(cfg.data.output_dir) / "pm_epa_player_leaderboards.csv"
    if lb.exists():
        d = pl.read_csv(lb).filter(pl.col("qualified_ev"))
        L += ["## 11. Leaderboard sample (face validity)", "", "Top 20 by 5v5 PM-EPA/60 per position, last three seasons, ≥ 500 5v5 minutes. 95% CI from game bootstrap. Full table: `data/outputs/pm_epa_player_leaderboards.csv`.", ""]
        for season in cfg.data.seasons[-3:]:
            for pos in ["F", "D"]:
                top = d.filter((pl.col("season") == season) & (pl.col("pos_group") == pos)).sort("pm_epa_per60_ev", descending=True).head(20)
                L += [f"### {season}-{(season + 1) % 100:02d} — {'Forwards' if pos == 'F' else 'Defense'}", "",
                      table(["#", "player", "team", "5v5 min", "PM-EPA/60", "95% CI", "direct/60", "pooled/60", "pctile"],
                            [[i + 1, r["player_name"], r["team"], f"{r['toi_ev']:.0f}", f(r["pm_epa_per60_ev"], 3), f"({f(r['uncertainty_ci_low_per60'], 3)}, {f(r['uncertainty_ci_high_per60'], 3)})",
                              f(r["pm_direct_per60_ev"], 3), f(r["pm_pooled_per60_ev"], 3), f(r["percentile_ev"], 1)] for i, r in enumerate(top.iter_rows(named=True))]), ""]
    return "\n".join(L)


