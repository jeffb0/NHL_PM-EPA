def _j(cfg, name):
    p = cfg.path(cfg.data.metrics_dir) / name
    return json.loads(p.read_text()) if p.exists() else None


def f(x, nd=3):
    if x is None:
        return "—"
    try:
        if x != x:  # NaN
            return "—"
    except TypeError:
        return str(x)
    return f"{x:.{nd}f}"


def table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def gate(ok: bool | None, partial: bool = False) -> str:
    if ok is None:
        return "n/a"
    return "PASS" if ok else ("PARTIAL" if partial else "FAIL")


